    val totalGamesCancelled: Int,
    val totalUniquePlayers: Int,
    val averagePlayersPerGame: Double,
    val peakConcurrentPlayers: Int,
    val totalPlaytimeSeconds: Long,
    val averageGameDuration: Double,
    val shortestGameDuration: Int,
    val longestGameDuration: Int,
    val totalKills: Int,
    val totalDeaths: Int,
    val averageKillsPerGame: Double,
    val highestKillsInGame: Int,
    val totalPillarsDestroyed: Int,
