data class PlayerArenaStats(
    val playerId: String,
    val arenaName: String,
    val gamesPlayed: Int,
    val gamesWon: Int,
    val gamesLost: Int,
    val gamesQuit: Int,
    val totalPlaytimeSeconds: Long,
    val bestPlacement: Int?,
    val worstPlacement: Int?,
    val averagePlacement: Double,
    val totalKills: Int,
    val totalDeaths: Int,
    val totalAssists: Int,
    val bestKillstreak: Int,
    val pillarsDestroyed: Int,
    val blocksBroken: Long,
    val blocksPlaced: Long,
    val fastestWinTime: Int?,
    val longestGameTime: Int,
    val currentWinStreak: Int,
    val bestWinStreak: Int,
    val currentLossStreak: Int,
    val arenaRating: Double,
    val ratingPeak: Double,
    val ratingChangeTotal: Int,
    val perfectGames: Int,
    val comebackWins: Int,
    val dominantWins: Int,
    val firstPlayed: LocalDateTime,
    val lastPlayed: LocalDateTime,
    val favoriteSpawnPosition: Int?,
    val createdAt: LocalDateTime,
    val updatedAt: LocalDateTime
) {
    fun getWinRate(): Double = if (gamesPlayed > 0) (gamesWon * 100.0 / gamesPlayed) else 0.0
    fun getKDRatio(): Double = if (totalDeaths > 0) (totalKills.toDouble() / totalDeaths) else totalKills.toDouble()
}

